"""Rebuild RESULTS.md and results_summary.csv from the archived JSON files."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read_reports():
    """Read standalone reports once; comparison JSON embeds duplicate copies."""
    for path in sorted((ROOT / 'benchmark_results').rglob('*.json')):
        report = json.loads(path.read_text(encoding='utf-8'))
        if report.get('schema_version') == 2 and 'performance' in report:
            yield path, report


def main():
    rows = []
    for path, report in read_reports():
        settings, perf = report['settings'], report['performance']
        hardware = report['hardware'].get('gpu_vram_used_gib') or {}
        rows.append({
            'report': path.relative_to(ROOT).as_posix(),
            'label': report['label'],
            'requests_per_round': settings['prompts_per_round'],
            'rounds': settings['rounds'],
            'max_tokens': settings['sampling']['max_tokens'],
            'sequence_cap': settings['engine']['max_num_seqs'],
            'output_tokens_s': perf['aggregate_output_tokens_s'],
            'workload_ttft_p95_s': (perf.get('workload_ttft_s') or {}).get('p95'),
            'workload_latency_p95_s': (perf.get('workload_latency_s') or {}).get('p95'),
            'peak_gpu_vram_gib': hardware.get('peak'),
            'length_limited_outputs': perf['length_limited_outputs'],
            'completed_requests': perf['request_count'],
        })
    if not rows:
        raise ValueError('No archived standalone reports found')
    with (ROOT / 'results_summary.csv').open('w', newline='', encoding='utf-8') as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    lines = [
        '# Saved benchmark results', '',
        'Generated by `python summarize_results.py` from the standalone JSON reports. '
        'Suite comparison files embed the same reports and are not counted again.', '',
        'All runs use the NVIDIA GeForce RTX 5070 Ti Laptop GPU and '
        '`sanskar003/Qwen3.5-9B-AWQ`. Times are seconds; throughput is aggregate output '
        'tokens/s. Workload p95 includes waiting from the round boundary. '
        '`N/A` means that metric was not saved in that report.', '',
        'The 8-token suite is a smoke test. Compare rows with matching request counts, '
        'rounds, and token budgets. Capped outputs are responses that hit the output '
        'token limit, shown as a fraction of completed requests.', '',
    ]
    previous = None
    for row in rows:
        path = Path(row['report'])
        group = path.parts[1] if len(path.parts) > 2 else 'Standalone four-request runs'
        if group != previous:
            lines.extend(['## ' + group, '',
                '| Run | Requests/round | Rounds | Token budget | Cap | Output tok/s | Workload TTFT p95 | Workload latency p95 | Peak VRAM GiB | Capped outputs |',
                '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'])
            previous = group
        def number(key):
            value = row[key]
            return 'N/A' if value is None else f'{value:.2f}'
        lines.append(
            f"| [{row['label']}]({row['report']}) | {row['requests_per_round']} | "
            f"{row['rounds']} | {row['max_tokens']} | {row['sequence_cap']} | "
            f"{number('output_tokens_s')} | {number('workload_ttft_p95_s')} | "
            f"{number('workload_latency_p95_s')} | {number('peak_gpu_vram_gib')} | "
            f"{row['length_limited_outputs']}/{row['completed_requests']} |")
        # A blank line before the next group's heading is added below.
    text = '\n'.join(lines).replace('\n## ', '\n\n## ') + '\n'
    (ROOT / 'RESULTS.md').write_text(text, encoding='utf-8')
    print(f'Summarized {len(rows)} standalone reports.')


if __name__ == '__main__':
    main()
